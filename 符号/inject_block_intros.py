def main():
	with open(TAG_FILE, encoding='utf-8') as f:
		data = json.load(f)
	blocks = data['roots']['区块']['children']

	added = 0
	missing = []
	for name, intro in INTROS.items():
		if name in blocks:
			if not blocks[name].get('intro'):
				blocks[name]['intro'] = intro
				added += 1
		else:
			missing.append(name)

	with open(TAG_FILE, 'w', encoding='utf-8', newline='\n') as f:
		json.dump(data, f, ensure_ascii=False, indent=2)
		f.write('\n')

	print(f'注入 {added} 个 intro')
	if missing:
		print(f'INTROS 里找不到的区块名 {len(missing)} 个:')
		for m in missing:
			print(f'  {m}')


if __name__ == '__main__':
	main()




